#!/bin/sh
# Lists the licence of every Rust dependency that ends up on Linux (THIRD-PARTY-LICENSES.txt).
set -eu
{
  echo "Third-party software in this application"
  echo "========================================"
  echo
  echo "Font: Ubuntu Light, Ubuntu Font Licence 1.0 (full text: licenses/UFL.txt)."
  echo "Font: Inter, SIL Open Font License 1.1 (full text: licenses/Inter-LICENSE.txt)."
  echo "Font: JetBrains Mono, SIL Open Font License 1.1 (full text: licenses/JetBrainsMono-OFL.txt)."
  echo
  echo "Rust crates (name version: licence), generated by scripts/licenses.sh:"
  echo
  cargo metadata --format-version 1 --locked --filter-platform x86_64-unknown-linux-gnu 2>/dev/null \
    | python3 -c '
import json,sys
m=json.load(sys.stdin)
ids={n["id"] for n in m["resolve"]["nodes"]}
rows=sorted((p["name"],p["version"],p.get("license") or "see crate") for p in m["packages"] if p["id"] in ids and not p["source"] is None)
for n,v,l in rows: print(f"{n} {v}: {l}")
'
} > THIRD-PARTY-LICENSES.txt
wc -l THIRD-PARTY-LICENSES.txt
